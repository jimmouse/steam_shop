const DICTS: Record<SupportedLocale, Dict> = { zh, en, ru, ar };
const ENUMS: Record<SupportedLocale, Record<string, string>> = {
  zh: zhMessages.enum,
  en: enMessages.enum,
  ru: ruMessages.enum,
  ar: arMessages.enum,
};

export const LOCALE_NAMES: Record<SupportedLocale, string> = { zh: "中文", en: "English", ru: "Русский", ar: "العربية" };

export function t(locale: SupportedLocale, key: BotKey, vars: Record<string, string | number> = {}): string {
  const template = DICTS[locale]?.[key] ?? DICTS.en[key];
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

/** 订单状态 / 商品类型 / 支付方式等枚举的显示名 */
export function tEnum(locale: SupportedLocale, value: string): string {
  return ENUMS[locale]?.[value] ?? ENUMS.en[value] ?? value;
}

const STATUS_ICON: Record<string, string> = {
  PENDING: "⏳",
  PAID: "💰",
  PROCESSING: "🔧",
  DELIVERED: "✅",
  EXPIRED: "⌛",
  CANCELLED: "🚫",
  REFUNDED: "↩️",
};

export function statusLabel(locale: SupportedLocale, status: string): string {
  return `${STATUS_ICON[status] ?? ""} ${tEnum(locale, status)}`.trim();
}
